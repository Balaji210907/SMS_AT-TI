import { createFileRoute, Link } from "@tanstack/react-router";
import { useState } from "react";
import { supabase } from "@/integrations/supabase/client";
import { useData } from "@/lib/data";
import { date, money } from "@/lib/format";
import { mfrom, mt, useMode } from "@/lib/mode";
import { Empty, ErrorBox, Loading, PageHeader, Panel, StatusBadge, td, th } from "@/components/app/ui";
import { Input } from "@/components/ui/input";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";

export const Route = createFileRoute("/_authenticated/app/invoices/")({ component: Invoices });

function Invoices() {
  const { mode, isDemo } = useMode();
  const [status, setStatus] = useState("all");
  const [q, setQ] = useState("");
  const list = useData<any[]>(["invoices", mode, status], () => {
    const subEmbed = isDemo ? "subscriptions:demo_subscriptions!demo_invoices_subscription_id_fkey(subscription_number)" : "subscriptions!invoices_subscription_id_fkey(subscription_number)";
    let r = mfrom(mode, "invoices").select(`id, invoice_number, invoice_date, due_date, total, amount_paid, status, customer_snapshot, ${subEmbed}`).order("invoice_date", { ascending: false }).order("invoice_number", { ascending: false });
    if (status !== "all") r = r.eq("status", status as never);
    return r;
  });
  const rows = (list.data ?? []).filter((i) => !q || `${i.invoice_number} ${(i.customer_snapshot as { name?: string })?.name}`.toLowerCase().includes(q.toLowerCase()));
  return (
    <>
      <PageHeader title="Invoices" description={isDemo ? "Demo Mode — sample invoices are read-only here." : "Generated by billing runs. Financial details are frozen once issued."} />
      <Panel>
        <div className="flex flex-wrap gap-2 border-b p-3">
          <Input placeholder="Search invoice or customer…" value={q} onChange={(e) => setQ(e.target.value)} className="max-w-xs" />
          <Select value={status} onValueChange={setStatus}><SelectTrigger className="w-40"><SelectValue /></SelectTrigger>
            <SelectContent>{["all", "draft", "confirmed", "partially_paid", "paid", "overdue", "cancelled"].map((s) => <SelectItem key={s} value={s} className="capitalize">{s.replace("_", " ")}</SelectItem>)}</SelectContent></Select>
        </div>
        {list.isLoading ? <Loading /> : list.error ? <ErrorBox error={list.error} /> : !rows.length ? <Empty title="No invoices" /> : (
          <div className="overflow-x-auto"><table className="w-full">
            <thead className="border-b bg-muted/40"><tr><th className={th}>Invoice</th><th className={th}>Customer</th><th className={th}>Date</th><th className={th}>Due</th><th className={th}>Status</th><th className={`${th} text-right`}>Total</th><th className={`${th} text-right`}>Outstanding</th></tr></thead>
            <tbody className="divide-y">{rows.map((i) => (
              <tr key={i.id} className="hover:bg-muted/30">
                <td className={td}><Link to="/app/invoices/$id" params={{ id: i.id }} className="font-medium text-primary">{i.invoice_number}</Link><div className="text-xs text-muted-foreground">{i.subscriptions?.subscription_number}</div></td>
                <td className={td}>{(i.customer_snapshot as { name?: string })?.name}</td>
                <td className={td}>{date(i.invoice_date)}</td>
                <td className={td}>{date(i.due_date)}</td>
                <td className={td}><StatusBadge status={i.status} /></td>
                <td className={`${td} num text-right`}>{money(i.total)}</td>
                <td className={`${td} num text-right`}>{i.status === "cancelled" ? "—" : money(Number(i.total) - Number(i.amount_paid))}</td>
              </tr>))}</tbody>
          </table></div>
        )}
      </Panel>
    </>
  );
}
